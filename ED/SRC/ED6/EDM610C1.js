//處理呼叫子視窗回傳值
function CallBack(argCallerId)
{
	
	if(argCallerId == "EDM610C1")
	{
		document.all["txSuppCode"].value = jf_Trim(document.all.lbReturnValue.options[0].value);
		document.all["txSuppNotes"].value = jf_Trim(document.all.lbReturnValue.options[1].value);
		if(document.all["txSuppCode"].value != "")
		{
			Page_BlockSubmit=false;
			jf_OpenButtonSubmit();
		}
	    /*1050505 Justin 1050087 二代公文修改
		document.all["txSuppCode"].focus();*/
		$('#txSuppCode').focus();
	}
	
	
	//清空lbReturnValue物件
	if(document.all["lbReturnValue"].options != null)
		document.all["lbReturnValue"].options.length = 0;
}

//組出回傳值
function ReturnValue(argLink, argRead1)
{
    
	try
	{
	    opener.document.all.lbReturnValue.length = 2;
	    opener.document.all.lbReturnValue.options[0].value = argLink;
	    opener.document.all.lbReturnValue.options[1].value = argRead1;
	    opener.window.CallBack("EDM610C1");
	    close();
	}
	catch (e) {}
    
}

